"""
OULU-NPU protocol-aware dataset.

Usage
-----
from dataset_oulu import OULUProtocolDataset, collate_fn

# Protocol 1 — single train split
train_ds = OULUProtocolDataset("protocol_csvs/Protocol_1/Train.csv", transform=..., is_train=True)

# Protocol 3 — leave-one-camera-out, fold 2
train_ds = OULUProtocolDataset("protocol_csvs/Protocol_3/Train_2.csv", transform=..., is_train=True)
dev_ds   = OULUProtocolDataset("protocol_csvs/Protocol_3/Dev_2.csv",   transform=...)
test_ds  = OULUProtocolDataset("protocol_csvs/Protocol_3/Test_2.csv",  transform=...)

Labels: 1 = real, 0 = attack  (consistent with original VideoDataset)
"""

import os
import csv
import numpy as np
import torch
from torch.utils.data import Dataset
import cv2
from torchvision.transforms import functional as TF


class OULUProtocolDataset(Dataset):
    """
    Loads OULU-NPU videos from a protocol CSV generated by generate_protocol_csvs.py.

    CSV must have columns: filepath, label  (other columns are ignored)

    Parameters
    ----------
    csv_path    : path to the protocol CSV file
    transform   : callable applied to each frame tensor (C,H,W)
    num_frames  : how many frames to sample per video
    is_train    : if True, samples a random temporal window; else uses the start
    attack_types: optional list of attack_type strings to restrict to
                  e.g. ["real", "print1"] — None means keep all
    """

    CLASSES = ["attack", "real"]  # index 0 = attack, 1 = real

    def __init__(
        self,
        csv_path: str,
        transform=None,
        num_frames: int = 16,
        is_train: bool = False,
        attack_types: list[str] | None = None,
    ):
        self.csv_path = csv_path
        self.transform = transform
        self.num_frames = num_frames
        self.is_train = is_train
        self.samples = self._load_csv(csv_path, attack_types)

    def _load_csv(self, csv_path: str, attack_types: list[str] | None) -> list[tuple]:
        samples = []
        with open(csv_path, newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if attack_types is not None and row.get("attack_type") not in attack_types:
                    continue
                samples.append((row["filepath"], int(row["label"])))
        return samples

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        video_path, label = self.samples[idx]
        frames = self._load_frames(video_path)

        if self.transform:
            frames = [self.transform(frame) for frame in frames]

        return torch.stack(frames), label

    def _load_frames(self, video_path: str) -> list[torch.Tensor]:
        cap = cv2.VideoCapture(video_path)
        total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

        if self.is_train:
            start = np.random.randint(0, max(1, total - self.num_frames + 1))
        else:
            start = 0

        cap.set(cv2.CAP_PROP_POS_FRAMES, start)
        frames = []
        for _ in range(self.num_frames):
            ret, frame = cap.read()
            if not ret:
                break
            frames.append(TF.to_tensor(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)))
        cap.release()

        # pad with last frame (or blank) to reach num_frames
        if len(frames) == 0:
            frames.append(torch.zeros(3, 256, 256))
        while len(frames) < self.num_frames:
            frames.append(frames[-1])

        return frames


def collate_fn(batch):
    """Pads variable-length frame sequences to the longest in the batch."""
    max_t = max(f.size(0) for f, _ in batch)
    padded, labels = [], []
    for frames, label in batch:
        if frames.size(0) < max_t:
            pad = torch.zeros(max_t - frames.size(0), *frames.shape[1:])
            frames = torch.cat([frames, pad], dim=0)
        padded.append(frames)
        labels.append(label)
    return torch.stack(padded), torch.tensor(labels)


# ---------------------------------------------------------------------------
# Convenience factory: build train/dev/test loaders for a single protocol fold
# ---------------------------------------------------------------------------

from torch.utils.data import DataLoader
from pathlib import Path


def make_loaders(
    protocol_csv_dir: str,
    fold: int | None = None,
    transform_train=None,
    transform_eval=None,
    num_frames: int = 16,
    batch_size: int = 32,
    num_workers: int = 4,
    attack_types: list[str] | None = None,
) -> dict[str, DataLoader]:
    """
    Build DataLoaders for one protocol fold.

    protocol_csv_dir : e.g. "protocol_csvs/Protocol_1" or "protocol_csvs/Protocol_3"
    fold             : 1..6 for protocols 3/4 (leave-one-camera-out); None for protocols 1/2
    """
    base = Path(protocol_csv_dir)
    suffix = f"_{fold}" if fold is not None else ""

    def _loader(split: str, is_train: bool) -> DataLoader:
        csv_path = base / f"{split}{suffix}.csv"
        ds = OULUProtocolDataset(
            str(csv_path),
            transform=transform_train if is_train else transform_eval,
            num_frames=num_frames,
            is_train=is_train,
            attack_types=attack_types,
        )
        return DataLoader(
            ds,
            batch_size=batch_size,
            shuffle=is_train,
            num_workers=num_workers,
            collate_fn=collate_fn,
            pin_memory=True,
        )

    loaders = {
        "train": _loader("Train", is_train=True),
        "dev":   _loader("Dev",   is_train=False),
        "test":  _loader("Test",  is_train=False),
    }
    return loaders
